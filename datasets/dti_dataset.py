from pathlib import Path

import numpy as np
import pandas as pd

import torch
from torch.utils.data import Dataset


class DTIDataset(Dataset):
    """
    IMPORTANT — why lookups go through strings, not integer ids:
    --------------------------------------------------------------
    Each split's smiles.csv / sequence.csv restarts its "index" column at
    0, so a "smiles_id"/"protein_id" value in samples.csv is only valid
    *within that split's own smiles.csv / sequence.csv*. It is NOT a safe
    key into the global feature files (morgan_fingerprints.npz /
    psepssm_features.npz), which are deduplicated and keyed by the actual
    SMILES string / protein sequence string.

    Correct lookup path for every sample:

        sample -> local smiles_id  -> (this split's smiles.csv)   -> SMILES string   -> fingerprint
        sample -> local protein_id -> (this split's sequence.csv) -> sequence string -> PsePSSM vector

    Using the split-local integer id directly against the global npz
    files (the previous behaviour) silently collides different molecules
    / proteins that happen to share the same local index across splits,
    which is what produced train ROC ~0.99 / valid ROC ~0.50.
    """

    def __init__(
        self,
        samples_csv,
        protein_features_npz,
        drug_features_npz
    ):

        samples_csv = Path(samples_csv)
        split_dir = samples_csv.parent

        # --------------------------------------------------
        # Interaction samples
        # --------------------------------------------------

        self.samples = pd.read_csv(samples_csv)

        self.samples = self.samples.rename(
            columns={
                "sequence": "protein_id",
                "smiles": "smiles_id",
                "interactions": "label"
            }
        )

        # --------------------------------------------------
        # Split-local id -> string maps.
        #
        # These come from THIS split's own smiles.csv / sequence.csv
        # (siblings of samples_csv), never from a global/concatenated
        # file, since the ids are only meaningful within their split.
        # --------------------------------------------------

        split_smiles = pd.read_csv(split_dir / "smiles.csv")
        split_sequence = pd.read_csv(split_dir / "sequence.csv")

        assert split_smiles["index"].duplicated().sum() == 0, (
            f"Duplicate indices in {split_dir / 'smiles.csv'}"
        )
        assert split_sequence["index"].duplicated().sum() == 0, (
            f"Duplicate indices in {split_dir / 'sequence.csv'}"
        )

        self._local_id_to_smiles = dict(
            zip(split_smiles["index"], split_smiles["smiles"])
        )
        self._local_id_to_sequence = dict(
            zip(split_sequence["index"], split_sequence["sequence"])
        )

        # --------------------------------------------------
        # Protein features: sequence string -> PsePSSM vector
        # --------------------------------------------------

        protein_data = np.load(protein_features_npz, allow_pickle=True)

        if "sequence" not in protein_data.files:
            raise ValueError(
                f"{protein_features_npz} does not contain a 'sequence' "
                "array. It was generated by the old, sequence_id-keyed "
                "pipeline. Re-run scripts/04_generate_psepssm.py to "
                "regenerate it with sequence-string keys (this reuses "
                "the existing PSSM files — no PSI-BLAST rerun needed)."
            )

        protein_sequences = protein_data["sequence"]
        protein_features = protein_data["features"]

        assert len(protein_sequences) == len(set(protein_sequences)), (
            "Duplicate protein sequences found in "
            f"{protein_features_npz} — the PsePSSM feature file is "
            "corrupt and must be regenerated."
        )

        self.protein_lookup = {
            seq: feat
            for seq, feat in zip(protein_sequences, protein_features)
        }

        # --------------------------------------------------
        # Drug features: SMILES string -> Morgan fingerprint
        # --------------------------------------------------

        drug_data = np.load(drug_features_npz, allow_pickle=True)

        if "smiles" not in drug_data.files:
            raise ValueError(
                f"{drug_features_npz} does not contain a 'smiles' array. "
                "Re-run scripts/03_generate_morgan_fingerprints.py to "
                "regenerate it with SMILES-string keys."
            )

        drug_smiles = drug_data["smiles"]
        drug_features = drug_data["fingerprints"]

        assert len(drug_smiles) == len(set(drug_smiles)), (
            "Duplicate SMILES found in "
            f"{drug_features_npz} — the fingerprint feature file is "
            "corrupt and must be regenerated."
        )

        self.drug_lookup = {
            smi: feat
            for smi, feat in zip(drug_smiles, drug_features)
        }

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):

        row = self.samples.iloc[idx]

        sequence = self._local_id_to_sequence[row["protein_id"]]
        smiles = self._local_id_to_smiles[row["smiles_id"]]

        try:
            protein = self.protein_lookup[sequence]
        except KeyError:
            raise KeyError(
                f"No PsePSSM features for local protein_id="
                f"{row['protein_id']!r} (sequence not present in the "
                "PsePSSM feature file)."
            )

        try:
            drug = self.drug_lookup[smiles]
        except KeyError:
            raise KeyError(
                f"No fingerprint for local smiles_id="
                f"{row['smiles_id']!r} (SMILES not present in the "
                "fingerprint feature file)."
            )

        label = row["label"]

        return (
            torch.tensor(protein, dtype=torch.float32),
            torch.tensor(drug, dtype=torch.float32),
            torch.tensor(label, dtype=torch.float32)
        )
